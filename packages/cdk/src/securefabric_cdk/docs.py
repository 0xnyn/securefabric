"""Generated connector reference pages (NORM-10, CAT-03).

``securefabric-cdk docs <connector dir>`` renders ``docs/connectors/<id>.md`` from
the three things that define a connector's behaviour, so the page cannot drift:

- the manifest (auth, permissions, streams, options, actions),
- ``capabilities.json`` (values each stream really emits, field coverage),
- the connector's ``mapping.py`` tables (vendor value → canonical value), with the
  comment above each table as its explanation.

``--check`` fails when the committed page is stale (run in CI by the tooling test).
"""

import importlib.util
import json
import re
from enum import Enum
from pathlib import Path
from typing import Any

from securefabric_cdk.manifest import Manifest, load_manifest


def _plain(value: Any) -> Any:
    """JSON-able form: enum values, tuple keys joined, nested dicts and lists."""
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, dict):
        return {
            (" + ".join(str(_plain(x)) for x in k) if isinstance(k, tuple) else str(_plain(k))): (
                _plain(v)
            )
            for k, v in value.items()
        }
    if isinstance(value, (list, tuple)):
        return [_plain(v) for v in value]
    return value


def _cell(value: Any) -> str:
    if value is None:
        return "*(none)*"
    if isinstance(value, Enum):
        return f"`{value.value}`"
    if isinstance(value, tuple):
        return " + ".join(_cell(v) for v in value)
    if isinstance(value, list):
        return ", ".join(_cell(v) for v in value) or "-"
    if isinstance(value, dict):
        return "`" + json.dumps(_plain(value), sort_keys=True) + "`"
    return f"`{value}`"


def _duration(seconds: int | None) -> str:
    if not seconds:
        return "-"
    for unit, size in (("d", 86400), ("h", 3600), ("min", 60)):
        if seconds % size == 0:
            return f"{seconds // size} {unit}"
    return f"{seconds} s"


def _mapping_tables(directory: Path) -> list[tuple[str, str, dict[Any, Any]]]:
    """(name, comment, table) for every module-level dict in mapping.py."""
    path = directory / "mapping.py"
    if not path.exists():
        return []
    spec = importlib.util.spec_from_file_location(f"_sf_docs_{directory.name}_mapping", path)
    if spec is None or spec.loader is None:
        return []
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    source = path.read_text().splitlines()
    out: list[tuple[str, str, dict[Any, Any]]] = []
    for i, line in enumerate(source):
        m = re.match(r"^([A-Z][A-Z0-9_]*)\s*(?::[^=]+)?=\s*\{", line)
        if not m or not isinstance(getattr(module, m.group(1), None), dict):
            continue
        comment: list[str] = []
        j = i - 1
        while j >= 0 and source[j].startswith("#") and not source[j].startswith("# ---"):
            comment.insert(0, source[j].lstrip("# ").rstrip())
            j -= 1
        out.append((m.group(1), " ".join(comment), getattr(module, m.group(1))))
    return out


def render(directory: Path) -> tuple[Manifest, str]:
    manifest = load_manifest(directory / "manifest.yaml")
    caps_path = directory / "capabilities.json"
    caps = json.loads(caps_path.read_text()) if caps_path.exists() else {"streams": {}}
    a = manifest.auth
    lines = [
        f"# {manifest.display_name} (`{manifest.id}`)",
        "",
        "<!-- Generated by `securefabric-cdk docs` from manifest.yaml, capabilities.json and "
        "mapping.py. Do not edit by hand. -->",
        "",
        manifest.description.strip(),
        "",
        f"- **Version:** {manifest.version} ({manifest.status})",
        f"- **Auth:** `{a.mode.value}`, connected by {a.connect.value}"
        + (f", vendor app {a.vendor_app}" if a.vendor_app != "none" else ""),
    ]
    if a.oauth2:
        lines.append(
            f"- **OAuth2:** scopes {_cell(a.oauth2.scopes)}; PKCE {'on' if a.oauth2.pkce else 'off'}"
            + ("; single-use refresh tokens" if a.oauth2.single_use_refresh_tokens else "")
        )
    if manifest.regions:
        lines.append(
            "- **Regions:** " + ", ".join(f"`{r.id}` ({r.api_base})" for r in manifest.regions)
        )
    if manifest.billing_exempt:
        lines.append("- **Billing:** exempt (synthetic data)")
    lines.append("")

    if manifest.permissions:
        lines += [
            "## Permissions",
            "",
            "| Permission | Access | Needed for | Optional |",
            "|---|---|---|---|",
        ]
        for p in manifest.permissions:
            lines.append(
                f"| `{p.name}` | {p.access} | {_cell([*p.streams, *p.actions])} | "
                f"{'yes' if p.optional else 'no'} |"
            )
        lines.append("")

    lines += [
        "## Streams",
        "",
        "| Stream | Object | Types | Sync | Interval (default, range) | Full pass | Deletion | "
        "Min. version |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s in manifest.streams:
        types = s.finding_types or s.resource_types
        lines.append(
            f"| `{s.name}` | {s.object} | {_cell(types)} | {s.sync_mode.value} | "
            f"{_duration(s.interval.default)} ({_duration(s.interval.min)}-"
            f"{_duration(s.interval.max)}) | {_duration(s.full_every)} | {s.deletion.value} | "
            f"{s.min_vendor_version or '-'} |"
        )
    lines.append("")

    for s in manifest.streams:
        c = caps.get("streams", {}).get(s.name)
        if not c and not s.capabilities and not s.webhook_events:
            continue
        lines += [f"### `{s.name}`", ""]
        if s.title:
            lines += [s.title, ""]
        if s.webhook_events:
            lines += [f"Webhook events: {_cell(s.webhook_events)}.", ""]
        if s.capabilities:
            lines += ["| Field | Supported | Notes |", "|---|---|---|"]
            for f, cap in sorted(s.capabilities.items()):
                lines.append(f"| `{f}` | {'yes' if cap.supported else 'no'} | {cap.notes or ''} |")
            lines.append("")
        if c:
            lines += [
                f"Measured on {c['records']} golden records:",
                "",
                "| Field | Values emitted | Coverage |",
                "|---|---|---|",
            ]
            fields = sorted(set(c.get("values_emitted", {})) | set(c.get("coverage", {})))
            for f in fields:
                cov = c.get("coverage", {}).get(f)
                emitted = c.get("values_emitted", {})
                shown = _cell(emitted[f]) if f in emitted else "-"
                lines.append(f"| `{f}` | {shown} | {f'{cov:.0%}' if cov is not None else '-'} |")
            lines.append("")

    props = (manifest.options or {}).get("properties") or {}
    if props:
        lines += [
            "## Options",
            "",
            "| Option | Values | Default | Description |",
            "|---|---|---|---|",
        ]
        for name, p in props.items():
            values = p.get("enum") or p.get("type") or "-"
            desc = (p.get("description") or p.get("title") or "").replace("\n", " ").strip()
            lines.append(f"| `{name}` | {_cell(values)} | {_cell(p.get('default'))} | {desc} |")
        lines.append("")

    tables = _mapping_tables(directory)
    if tables:
        lines += [
            "## Mapping",
            "",
            "The connector's mapping tables, as code defines them (vendor value to canonical "
            "value, and the write-back requests).",
            "",
        ]
        for name, comment, table in tables:
            lines += [f"### {name.replace('_', ' ').capitalize()}", ""]
            if comment:
                lines += [comment, ""]
            values = list(table.values())
            if values and all(isinstance(v, dict) for v in values):
                # Nested (e.g. write-back: family -> canonical state + reason -> request).
                lines += ["| Group | Key | Value |", "|---|---|---|"]
                for group, inner in table.items():
                    for k, v in inner.items():
                        lines.append(f"| {_cell(group)} | {_cell(k)} | {_cell(v)} |")
            else:
                canonical = values and all(isinstance(v, Enum) for v in values)
                head = "| Vendor | Canonical |" if canonical else "| Key | Value |"
                lines += [head, "|---|---|"]
                for k, v in table.items():
                    lines.append(f"| {_cell(k)} | {_cell(v)} |")
            lines.append("")

    if manifest.actions:
        lines += ["## Actions (write-back)", ""]
        for act in manifest.actions:
            lines.append(f"- `{act.name}` on {act.object}")
        lines.append("")
    return manifest, "\n".join(lines).rstrip() + "\n"


def write_docs(directory: Path, out_dir: Path, *, check: bool) -> tuple[Path, bool]:
    """Write (or with ``check`` compare) the page. Returns (path, up to date)."""
    manifest, text = render(directory)
    target = out_dir / f"{manifest.id.lower()}.md"
    current = target.read_text() if target.exists() else None
    if check:
        return target, current == text
    out_dir.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    return target, True
